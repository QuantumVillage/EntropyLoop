#!/usr/bin/env python3
"""Compute SP 800-90B section 4.4 health-test cutoffs.

Repetition Count Test (4.4.1):  C = 1 + ceil(-log2(alpha) / H)
Adaptive Proportion Test (4.4.2): C = 1 + CRITBINOM(W, 2^-H, 1 - alpha)
  where CRITBINOM(n, p, q) is the smallest k with P(X <= k) >= q, X ~ Binomial(n, p).
  W = 1024 for binary sources, 512 otherwise.

H is the claimed min-entropy per sample (bits). alpha is the false-positive
probability per sample (90B recommends 2^-20 to 2^-40).

Exact rational arithmetic, no dependencies.

Usage:
  python3 tools/ht_cutoffs.py --h 4                # one value
  python3 tools/ht_cutoffs.py --table --c-header   # regenerate src/health_cutoffs.h
"""
import argparse
import math
from fractions import Fraction


def rct_cutoff(h: float, alpha_log2: int) -> int:
    return 1 + math.ceil(alpha_log2 / h)


def apt_cutoff(h: float, alpha_log2: int, window: int) -> int:
    # p = 2^-H. For integer H this is exact; otherwise use a close rational.
    if float(h).is_integer():
        p = Fraction(1, 2 ** int(h))
    else:
        p = Fraction(2.0 ** -h).limit_denominator(10 ** 15)
    q = 1 - p
    tail_target = Fraction(1, 2 ** alpha_log2)  # need P(X > k) <= alpha
    # Walk the CDF exactly.
    cdf = Fraction(0)
    term = q ** window  # P(X = 0)
    for k in range(window + 1):
        cdf += term
        if 1 - cdf <= tail_target:
            return 1 + k
        # P(X = k+1) = P(X = k) * (n-k)/(k+1) * p/q
        term = term * (window - k) * p / ((k + 1) * q)
    return window + 1


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--h", type=float, help="claimed min-entropy per sample, bits")
    ap.add_argument("--alpha-log2", type=int, default=40, help="alpha = 2^-N (default 40)")
    ap.add_argument("--window", type=int, default=512)
    ap.add_argument("--table", action="store_true", help="table for H = 1..8")
    ap.add_argument("--c-header", action="store_true", help="emit as a C header")
    a = ap.parse_args()

    hs = list(range(1, 9)) if a.table else [a.h]
    rows = [(h, rct_cutoff(h, a.alpha_log2), apt_cutoff(h, a.alpha_log2, a.window)) for h in hs]

    if a.c_header:
        print("/* Generated by tools/ht_cutoffs.py --table --c-header"
              f" --alpha-log2 {a.alpha_log2} --window {a.window}. Do not edit. */")
        print("#ifndef HEALTH_CUTOFFS_H\n#define HEALTH_CUTOFFS_H\n")
        print(f"#define HT_ALPHA_LOG2 {a.alpha_log2}")
        print(f"#define HT_APT_WINDOW {a.window}\n")
        print("/* index = claimed H in whole bits (1..8); index 0 unused */")
        print("static const unsigned short HT_RCT_CUTOFF[9] = {0, "
              + ", ".join(str(r[1]) for r in rows) + "};")
        print("static const unsigned short HT_APT_CUTOFF[9] = {0, "
              + ", ".join(str(r[2]) for r in rows) + "};")
        print("\n#endif")
    else:
        print(f"alpha = 2^-{a.alpha_log2}, APT window = {a.window}")
        print("H  RCT_cutoff  APT_cutoff")
        for h, r, p in rows:
            print(f"{h:<3}{r:<12}{p}")


if __name__ == "__main__":
    main()
